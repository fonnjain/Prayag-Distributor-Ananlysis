// Phase A2 — Salesperson narrative report.
//
// Calls POST /api/ai/report, renders the six-section report, shows the numeric
// guard status, and provides a Download PDF button (window.print()).
//
// Architecture: app = numbers. Claude = judgement.
// Every number in the rendered text was checked by the server-side numeric guard
// before reaching this component. If guard.status === "requires_review", an
// orange banner lists the flagged figures.

import { useState } from "react";
import { cn } from "@/lib/utils";

const BASE = import.meta.env.BASE_URL ?? "/";
const API  = `${BASE}api`.replace(/\/\//g, "/");

// ── Types ─────────────────────────────────────────────────────────────────────

interface ReportSection {
  title: string;
  body:  string;
}

interface UnmatchedNumber {
  extracted: string;
  value:     number;
  sentence:  string;
}

interface GuardResult {
  status:    "ok" | "requires_review";
  checked:   number;
  unmatched: UnmatchedNumber[];
}

interface AiReport {
  fy:          string;
  member:      string;
  stateHead:   string | null;
  dataCutoff:  string;
  generatedAt: string;
  sections: {
    executiveSummary:         ReportSection;
    performanceAgainstTarget: ReportSection;
    coverageAndCustomerBase:  ReportSection;
    visitEffectiveness:       ReportSection;
    costAndReturn:            ReportSection;
    risksAndDataCaveats:      ReportSection;
  };
  guard:           GuardResult;
  corruptTestMode?: boolean;
}

// ── Props ─────────────────────────────────────────────────────────────────────

interface Props {
  fy:         string;
  stateHead:  string;
  memberKey:  string;   // normKey
  memberName: string;
}

// ── Guard status badge ────────────────────────────────────────────────────────

function GuardStatusBadge({
  guard,
  corrupt,
}: {
  guard:   GuardResult;
  corrupt: boolean;
}) {
  if (guard.status === "ok" && !corrupt) {
    return (
      <div className="no-print flex items-center gap-2 rounded-md border border-green-600/30 bg-green-50 px-3 py-2 text-sm text-green-800">
        <span className="font-semibold">Numeric guard:</span>
        <span>{guard.checked} tokens checked — zero unmatched. Report is cleared for review.</span>
      </div>
    );
  }

  return (
    <div className="no-print flex flex-col gap-2 rounded-md border border-amber-500/40 bg-amber-50 px-3 py-2 text-sm text-amber-900">
      <div className="flex items-center gap-2">
        <span className="font-semibold">
          {corrupt ? "Guard test — MISMATCH DETECTED (expected)" : "Requires review"}
        </span>
        <span>
          {guard.unmatched.length} of {guard.checked} tokens could not be matched to the payload.
        </span>
      </div>
      {guard.unmatched.length > 0 && (
        <ul className="mt-1 space-y-1 pl-2 border-l-2 border-amber-400">
          {guard.unmatched.map((u, i) => (
            <li key={i} className="text-xs">
              <span className="font-mono font-bold">{u.extracted}</span>
              {" — "}
              <span className="italic">{u.sentence}</span>
            </li>
          ))}
        </ul>
      )}
    </div>
  );
}

// ── Single report section ─────────────────────────────────────────────────────

function Section({ section }: { section: ReportSection }) {
  return (
    <div className="report-section">
      <h2 className="report-section-title">{section.title}</h2>
      <div className="report-section-body">
        {section.body.split("\n\n").map((para, i) => (
          <p key={i} className="report-para">{para}</p>
        ))}
      </div>
    </div>
  );
}

// ── Full printable document ───────────────────────────────────────────────────

