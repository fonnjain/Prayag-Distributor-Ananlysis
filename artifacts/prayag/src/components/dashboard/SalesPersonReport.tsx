// ── Main component ────────────────────────────────────────────────────────────

export function SalesPersonReport({ fy, stateHead, memberKey, memberName }: Props) {
  const [report,  setReport]  = useState<AiReport | null>(null);
  const [loading, setLoading] = useState(false);
  const [error,   setError]   = useState<string | null>(null);

  async function generate(corrupt = false) {
    setLoading(true);
    setError(null);
    setReport(null);
    try {
      const res = await fetch(`${API}/ai/report`, {
        method:  "POST",
        headers: { "Content-Type": "application/json" },
        body:    JSON.stringify({ fy, stateHead, member: memberKey, period: "ytd", corrupt }),
      });
      if (!res.ok) {
        const body = await res.json().catch(() => ({})) as Record<string, unknown>;
        throw new Error(typeof body.error === "string" ? body.error : `Server error ${res.status}`);
      }
      const data = await res.json() as AiReport;
      setReport(data);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Report generation failed.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <div className="space-y-3">

      {/* Pre-generate prompt */}
      {!report && !loading && (
        <div className="flex flex-wrap gap-2 items-center no-print">
          <button
            onClick={() => void generate(false)}
            disabled={loading}
            className={cn(
              "h-9 rounded-md bg-primary px-4 text-sm font-medium text-primary-foreground",
              "hover:bg-primary/90 disabled:opacity-50",
            )}
          >
            Generate Report
          </button>
          <button
            onClick={() => void generate(true)}
            disabled={loading}
            title="Injects a wrong figure to prove the guard detects it"
            className={cn(
              "h-9 rounded-md border border-border bg-muted/40 px-4 text-sm",
              "hover:bg-muted/60 disabled:opacity-50",
            )}
          >
            Run Guard Test
          </button>
        </div>
      )}

      {/* Loading */}
      {loading && (
        <div className="rounded-md border border-border bg-muted/30 px-5 py-6 text-sm text-muted-foreground text-center">
          Generating report for {memberName} — this takes 15–30 seconds.
        </div>
      )}

      {/* Error */}
      {error && (
        <div className="rounded-md border border-destructive/30 bg-destructive/5 px-4 py-3 text-sm text-destructive">
          {error}
        </div>
      )}

      {/* Report actions + document */}
      {report && (
        <div className="space-y-3">

          {/* Action bar */}
          <div className="no-print flex flex-wrap gap-2 items-center">
            <button
              onClick={() => void generate(false)}
              className="h-8 rounded-md border border-border bg-muted/40 px-3 text-xs hover:bg-muted/60"
            >
              Regenerate
            </button>
            <button
              onClick={() => void generate(true)}
              title="Re-run guard test"
              className="h-8 rounded-md border border-border bg-muted/40 px-3 text-xs hover:bg-muted/60"
            >
              Guard Test
            </button>
            <button
              onClick={() => window.print()}
              className={cn(
                "h-8 rounded-md bg-primary px-4 text-xs font-medium text-primary-foreground",
                "hover:bg-primary/90",
              )}
            >
              Download PDF
            </button>
          </div>

          {/* Guard status */}
          <GuardStatusBadge
            guard={report.guard}
            corrupt={report.corruptTestMode ?? false}
          />

          {/* Report */}
          <ReportDocument report={report} />

        </div>
      )}

    </div>
  );
}
